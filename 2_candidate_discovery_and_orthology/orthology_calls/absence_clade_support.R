## deposit repo root: end
## Basis: the project's review of the literature on the sensitivity of absence calls names this
## as the first thing to do with the negatives ("Stratify negatives by phylogenetic
## support before anything else ... This requires no invented number and can be applied
## to our negatives today"), and makes it one of the two conditions that must both hold
## before losses may be counted. An uncertain state (0.5) is ambiguity, not absence, and
## absence of a signal is evidence only where the sensitivity of that signal is known.
##
## Phylogenetic support for every absence, following Deutekom et al. (2019).
##
## Deutekom, Vosseberg, van Dam and Snel (PLoS Comput Biol 2019; 15(8):e1007301;
## PMID 31461468; doi 10.1371/journal.pcbi.1007301) measured that clade-specific absences
## are falsely inferred 1.30% of the time, against 16.88% for species-specific absences,
## across 199 six-frame translated eukaryotic genomes ("more than a 10-fold difference").
## The definition is taken word for word from the Materials and methods of that paper,
## not from a summary of it:
##
##   "We analysed events in the leaves of Pfam domain trees generated by Dollo
##    parsimony. Leaves with ancestral losses (Pfam loss in parent node) are defined as
##    clade-specific absences. Leaves with single (independent) losses (Pfam present in
##    parent node) are defined as species-specific losses."
##
## and from its Results: "Clade-specific absences are supported by an ancestral loss,
## meaning they are supported by absences in one or more directly related species with
## independently sequenced and annotated genomes. Species-specific absences are not
## supported by losses in directly related species."
##
## The rule is therefore the state of the parent node and nothing else: no threshold, no
## cut-off, no free parameter. That is why the literature review says it "requires no
## invented number".
##
## Dollo parsimony is used because the cited measurement used it: one gain, losses
## minimised. For a character present at the root this reconstruction is exact and needs
## no library and no optimisation: an internal node has state 1 if and only if at least one
## descendant tip is an accepted member. It follows, as a property rather than an accident,
## that under Dollo no gain branch can exist below the root, so a gain column would be all
## zeros and is not written. A Fitch most-parsimonious reconstruction (MPR) is computed
## alongside as a model-free cross-check, and the two support classifications are reported
## side by side rather than reconciled.
##
## An undetermined tip is neither an absence nor a presence. The 28 proteomes in which
## absence cannot be assessed (absence_callable = no), and every species whose only hits the
## clade criterion could not place, count on neither side: they do not make a sister lineage
## look absent and they do not rescue one. This is the rule that an uncertain state is
## ambiguity, not absence, applied at the tip, and it is why SISTER_N_UNDET is a column of
## its own rather than being folded into one of the other two.
##
## This script makes no claim of loss. It computes the stratification that must precede any
## loss claim, and nothing else. It leaves the standing rules untouched: no absence frequency
## is compared across supergroups here, no recall is converted into a probability of
## absence, and no row is a probability for a single call.

