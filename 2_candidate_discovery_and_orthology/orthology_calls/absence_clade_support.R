CH  <- paste0(.TA210_SCRATCH, "/concord/ms210/P04b_chronogram")
P04 <- paste0(.TA210_SCRATCH, "/concord/ms210/P04_tree")
INDEX <- paste0(.TA210_HOME_REAL, "/ref/proteomes/proteome_index.tsv")
FINAL <- file.path(ROOT, "04_final_tables", "FINAL_ORTHOLOG_TABLE.tsv")
OUTD  <- file.path(ROOT, "07_findings")
OUT_S <- file.path(OUTD, "ABSENCE_SUPPORT_STRATIFICATION.tsv")
OUT_B <- file.path(OUTD, "TARGET_LOSS_BRANCHES.tsv")

TARGETS <- c("TOR", "RAPTOR", "RICTOR", "LST8", "AMPKa", "AMPKb", "AMPKg", "SIN1")
UNPLACED <- c("AMBIGUOUS", "NOT_PLACEABLE", "USED_AS_BOUNDARY_MARKER")
TREES  <- c(rooted_A2   = file.path(CH, "rooted_A2.treefile"),
            chronogram  = file.path(CH, "species_chronogram_209.treefile"),
            pmsf_constr = file.path(P04, "p04_pmsf_209_constr.treefile"),
            guide_209   = file.path(P04, "guide_209.treefile"),
            au_209      = file.path(P04, "p04_au_209.treefile"))
MIDPOINT_ALSO <- c("rooted_A2", "pmsf_constr")

md5 <- function(p) vapply(p, function(x)
  tryCatch(unname(tools::md5sum(path.expand(x))[[1]]),
           error = function(e) "UNREADABLE"), character(1))

read_nohash <- function(p) {
  L <- readLines(p, warn = FALSE)
  read.delim(text = L[!startsWith(L, "##")], stringsAsFactors = FALSE,
             quote = "", check.names = FALSE)
}

## ---- State of each target in each species, computed exactly as rl_presence_absence.py does
idx <- read.delim(INDEX, stringsAsFactors = FALSE, quote = "", check.names = FALSE)
idx$SPECIES <- sub("\\.faa$", "", idx$file)
if (nrow(idx) != 210) stop("REFUSED: corpus index gave ", nrow(idx), " species, expected 210")

fin <- read_nohash(FINAL)
for (cc in c("TARGET", "SPECIES", "IS_ORTHOLOG", "DISPOSITION"))
  if (!cc %in% names(fin)) stop("REFUSED: ", FINAL, " has no ", cc, " column")

present <- split(fin$SPECIES[fin$IS_ORTHOLOG == "yes"],
                 fin$TARGET[fin$IS_ORTHOLOG == "yes"])
unres <- split(fin$SPECIES[fin$DISPOSITION %in% UNPLACED],
               fin$TARGET[fin$DISPOSITION %in% UNPLACED])
if (length(present) == 0L) stop("REFUSED: no IS_ORTHOLOG=yes rows in ", FINAL)

callable <- setNames(trimws(idx$absence_callable) == "yes", idx$SPECIES)
supergrp <- setNames(trimws(idx$supergroup), idx$SPECIES)
cladev   <- setNames(trimws(idx$clade), idx$SPECIES)
gradev   <- setNames(trimws(idx$data_grade), idx$SPECIES)

state_of <- function(tg, sp) {
  if (sp %in% present[[tg]]) return("member")
  if (!isTRUE(callable[[sp]])) return("undet_inventory")
  if (sp %in% unres[[tg]]) return("undet_unplaced")
  "not_member"
}
STATE <- matrix("", nrow = length(TARGETS), ncol = nrow(idx),
                dimnames = list(TARGETS, idx$SPECIES))
for (tg in TARGETS) for (sp in idx$SPECIES) STATE[tg, sp] <- state_of(tg, sp)

## Every species must get exactly one state per target (this check once caught 114 false absences)
for (tg in TARGETS) {
  n <- table(factor(STATE[tg, ], levels = c("member", "not_member",
                                            "undet_unplaced", "undet_inventory")))
  if (sum(n) != 210)
    stop("REFUSED: ", tg, " states sum to ", sum(n), ", not 210")
}

## ---- Rooting, identical to rl_rm_asr.R so that the two analyses are comparable: the
## outgroup is the smaller of the two clades at the root of rooted_A2
ref <- read.tree(TREES[["rooted_A2"]])
rc  <- ref$edge[ref$edge[, 1] == Ntip(ref) + 1, 2]
d1  <- if (rc[1] <= Ntip(ref)) ref$tip.label[rc[1]] else extract.clade(ref, rc[1])$tip.label
d2  <- if (rc[2] <= Ntip(ref)) ref$tip.label[rc[2]] else extract.clade(ref, rc[2])$tip.label
OUTGROUP <- if (length(d1) <= length(d2)) d1 else d2

jobs <- list()
for (tn in names(TREES)) {
  jobs[[length(jobs) + 1]] <- list(tn = tn, mode = "auto")
  if (tn %in% MIDPOINT_ALSO)
    jobs[[length(jobs) + 1]] <- list(tn = tn, mode = "midpoint")
}

## ---- Dollo parsimony: a node has state 1 if and only if a descendant tip is an accepted member
dollo_states <- function(phy, tipmember) {
  nt <- Ntip(phy); nn <- phy$Nnode
  st <- integer(nt + nn)
  st[seq_len(nt)] <- as.integer(tipmember[phy$tip.label])
  ## postorder edge order: every child is visited before its parent
  e <- reorder(phy, "postorder")$edge
  for (i in seq_len(nrow(e))) if (st[e[i, 2]] == 1L) st[e[i, 1]] <- 1L
  st
}

mpr_states <- function(phy, ch) {
  pd <- phyDat(matrix(ch, ncol = 1, dimnames = list(phy$tip.label, NULL)),
               type = "USER", levels = c("0", "1"), ambiguity = "?")
  a <- try(ancestral.pars(phy, pd, type = "MPR"), silent = TRUE)
  if (inherits(a, "try-error")) return(NULL)
  m <- do.call(rbind, lapply(a, function(z) z[1, ]))
  ## a has one entry per tip and per internal node, so the result already has full length
  apply(m, 1, function(r) if (r[2] > r[1]) 1L else 0L)
}

srows <- list(); brows <- list()

for (jb in jobs) {
  tn <- jb$tn
  phy <- tryCatch(read.tree(TREES[[tn]]), error = function(e) NULL)
  if (is.null(phy)) { cat(sprintf("  SKIP %s: unreadable\n", tn)); next }
  phy <- keep.tip(phy, intersect(phy$tip.label, idx$SPECIES))
  og  <- intersect(OUTGROUP, phy$tip.label)
  if (jb$mode == "midpoint") {
    rootmode <- "midpoint_control"
    phy <- tryCatch(midpoint.root(phy), error = function(e) phy)
  } else if (length(og) > 0 && length(og) < Ntip(phy) && is.monophyletic(phy, og)) {
    rootmode <- "outgroup"
    phy <- tryCatch(root(phy, outgroup = og, resolve.root = TRUE),
                    error = function(e) phy)
  } else {
    rootmode <- "midpoint_forced_outgroup_not_monophyletic"
    phy <- tryCatch(midpoint.root(phy), error = function(e) phy)
  }
  if (!is.rooted(phy)) { cat(sprintf("  SKIP %s/%s: could not root\n", tn, rootmode)); next }
  cat(sprintf("  %-12s %-42s %d tips\n", tn, rootmode, Ntip(phy)))

  nt <- Ntip(phy); e <- phy$edge
  parent_of <- integer(nt + phy$Nnode); parent_of[e[, 2]] <- e[, 1]
  desc <- Descendants(phy, seq_len(nt + phy$Nnode), type = "tips")

  for (tg in TARGETS) {
    st_tip <- STATE[tg, phy$tip.label]
    memb <- setNames(as.integer(st_tip == "member"), phy$tip.label)
    ds <- dollo_states(phy, memb)
    ch <- ifelse(st_tip == "member", "1", ifelse(st_tip == "not_member", "0", "?"))
    ms <- mpr_states(phy, ch)
    ms_all <- if (is.null(ms) || length(ms) != nt + phy$Nnode)
      rep(NA_integer_, nt + phy$Nnode) else ms

    ## ---- per species -------------------------------------------------------------
    for (i in seq_len(nt)) {
      sp <- phy$tip.label[i]; v <- parent_of[i]
      sis <- setdiff(desc[[v]], i)
      sl <- st_tip[phy$tip.label[sis]]
      pdo <- ds[v]; pmp <- ms_all[v]
      is_abs <- st_tip[[sp]] == "not_member"
      sup_d <- if (!is_abs) "" else if (pdo == 1L) "SPECIES_SPECIFIC" else "CLADE_SUPPORTED"
      sup_m <- if (!is_abs || is.na(pmp)) "" else
        if (pmp == 1L) "SPECIES_SPECIFIC" else "CLADE_SUPPORTED"
      srows[[length(srows) + 1]] <- data.frame(
        TOPOLOGY = tn, ROOT_MODE = rootmode, TARGET = tg, SPECIES = sp,
        SUPERGROUP = supergrp[[sp]], CLADE = cladev[[sp]], DATA_GRADE = gradev[[sp]],
        ABSENCE_CALLABLE = ifelse(isTRUE(callable[[sp]]), "yes", "no"),
        STATE = st_tip[[sp]],
        PARENT_DOLLO = pdo, PARENT_MPR = pmp,
        SISTER_N_TIPS = length(sis),
        SISTER_N_MEMBER = sum(sl == "member"),
        SISTER_N_NOT_MEMBER = sum(sl == "not_member"),
        SISTER_N_UNDET = sum(sl %in% c("undet_inventory", "undet_unplaced")),
        SUPPORT_DOLLO = sup_d, SUPPORT_MPR = sup_m,
        stringsAsFactors = FALSE)
    }

    ## ---- per loss branch (parent state 1, child state 0 under Dollo) ---------------
    for (k in seq_len(nrow(e))) {
      p <- e[k, 1]; c <- e[k, 2]
      if (!(ds[p] == 1L && ds[c] == 0L)) next
      tips <- phy$tip.label[desc[[c]]]
      sl <- st_tip[tips]
      brows[[length(brows) + 1]] <- data.frame(
        TOPOLOGY = tn, ROOT_MODE = rootmode, TARGET = tg,
        BRANCH_IS_TERMINAL = ifelse(c <= nt, "yes", "no"),
        CHILD_NODE = c, N_TIPS_BELOW = length(tips),
        N_NOT_MEMBER = sum(sl == "not_member"),
        N_UNDET = sum(sl %in% c("undet_inventory", "undet_unplaced")),
        N_MEMBER = sum(sl == "member"),
        SUPERGROUPS_BELOW = paste(sort(unique(supergrp[tips])), collapse = ";"),
        CLADES_BELOW = paste(sort(unique(cladev[tips])), collapse = ";"),
        EXEMPLAR_TIPS = paste(head(sort(tips), 4), collapse = ";"),
        stringsAsFactors = FALSE)
    }
  }
}

S <- do.call(rbind, srows)
B <- if (length(brows)) do.call(rbind, brows) else
  stop("REFUSED: not one loss branch on any topology for any target; ",
       "that cannot be right and means the reconstruction is broken")
if (any(B$N_MEMBER > 0))
  stop("REFUSED: a Dollo loss branch has a member below it, which is impossible; ",
