wr <- function(f, hdr, df) {
  ftmp <- paste0(f, ".tmp"); con <- file(ftmp, "w")
  writeLines(c(hdr, prov), con); close(con)
  write.table(df, ftmp, sep = "\t", quote = FALSE, row.names = FALSE, append = TRUE)
  if (!file.rename(ftmp, f)) stop("REFUSED: could not rename ", ftmp, " over ", f)
}
